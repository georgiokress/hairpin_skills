#!/usr/bin/env python3
"""
Training-ready Sliding skill for a UR3e under ROS 2 Jazzy.

Methodical structure
--------------------
- Local ring frame F_R = {x_R, y_R, z_R}
    x_R: radial direction from start point toward stator centre
    y_R: circumferential direction
    z_R: surface normal
- Only z_R is compliant in force mode.
- Sliding along x_R is generated by a time-parameterised joint trajectory.
- Primary process parameters:
    normal_force_n, radial_speed_mps
- Detection parameters are fixed and logged separately.
- Every execution is stored as one CSV episode plus one JSON metadata file.

IMPORTANT SAFETY / CALIBRATION
------------------------------
1. This file intentionally does not invent inverse kinematics.
2. `slide_end_joints` must be calibrated for the selected slot/ring before use.
3. The resulting TCP path must be verified to be sufficiently radial in free space.
4. Begin with reduced robot speed and no workpiece contact.
5. The force sign and local z_R direction must be verified with a very small force.
"""

